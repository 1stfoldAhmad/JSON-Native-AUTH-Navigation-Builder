/**
 * @expo-foundation/auth - Auth Code Generator
 *
 * Implements Section 14.6, Section 16, and Audit Findings 6 & 15:
 * - Consolidates generated Auth runtime code around the canonical `@expo-foundation/auth`
 *   engine (`AuthController`, `ExpoSecureStoreAdapter`, `InMemoryTokenStorage`,
 *   `AuthProviderRegistry`).
 * - Never stores raw tokens in React component state or logs.
 */

import type { AuthIR } from '@expo-foundation/core';

export function generateAuthModuleFiles(ir: AuthIR): Record<string, string> {
  const files: Record<string, string> = {};

  files['src/foundation/auth/auth.config.ts'] = `/**
 * GENERATED BY @expo-foundation/auth - DO NOT EDIT MANUALLY
 */
import type { AuthIR } from '@expo-foundation/core';

export const AUTH_IR: AuthIR = ${JSON.stringify(ir, null, 2)} as unknown as AuthIR;
`;

  const usesSecureStore = ir.session.storage === 'secure-store';

  files['src/foundation/auth/AuthProvider.tsx'] = `/**
 * GENERATED BY @expo-foundation/auth - DO NOT EDIT MANUALLY
 *
 * Wraps the canonical @expo-foundation/auth AuthController and SessionManager
 * with ${usesSecureStore ? 'ExpoSecureStoreAdapter (expo-secure-store)' : 'InMemoryTokenStorage'}.
 */
import React, { createContext, useContext, useEffect, useMemo, useState, useCallback } from 'react';
${usesSecureStore ? `import * as SecureStore from 'expo-secure-store';` : ''}
import {
  AuthController,
  ${usesSecureStore ? 'ExpoSecureStoreAdapter' : 'InMemoryTokenStorage'},
  type AuthRuntimeSnapshot,
} from '@expo-foundation/auth';
import type {
  AuthProviderAdapter,
  EmailVerificationInput,
  MfaVerifyInput,
  OtpRequest,
  OtpVerification,
  PasswordResetInput,
  PasswordResetRequest,
  SignInInput,
  SignUpInput,
} from '@expo-foundation/contracts';
import { AUTH_IR } from './auth.config';

export interface AuthContextValue extends AuthRuntimeSnapshot {
  controller: AuthController;
  signIn: (input: SignInInput) => Promise<AuthRuntimeSnapshot>;
  signUp: (input: SignUpInput) => Promise<AuthRuntimeSnapshot>;
  signOut: () => Promise<AuthRuntimeSnapshot>;
  refreshSession: () => Promise<AuthRuntimeSnapshot>;
  verifyEmail: (input: EmailVerificationInput) => Promise<AuthRuntimeSnapshot>;
  requestOtp: (input: OtpRequest) => Promise<{ challengeId: string }>;
  verifyOtp: (input: OtpVerification) => Promise<AuthRuntimeSnapshot>;
  verifyMfa: (input: MfaVerifyInput) => Promise<AuthRuntimeSnapshot>;
  requestPasswordReset: (input: PasswordResetRequest) => Promise<void>;
  resetPassword: (input: PasswordResetInput) => Promise<void>;
  refreshAccessContextFromServer: () => Promise<AuthRuntimeSnapshot>;
}

const AuthContext = createContext<AuthContextValue | null>(null);

export interface AuthProviderProps {
  children: React.ReactNode;
  adapter?: AuthProviderAdapter;
}

export function AuthProvider({ children, adapter }: AuthProviderProps) {
  const controller = useMemo(() => {
    const storage = ${
      usesSecureStore
        ? 'new ExpoSecureStoreAdapter(SecureStore)'
        : 'new InMemoryTokenStorage()'
    };
    return new AuthController({
      authIR: AUTH_IR,
      adapter,
      storage,
    });
  }, [adapter]);

  const [snapshot, setSnapshot] = useState<AuthRuntimeSnapshot>(() =>
    controller.getSnapshot()
  );

  useEffect(() => {
    const unsubscribe = controller.subscribe((next) => {
      setSnapshot(next);
    });
    void controller.initialize();
    return unsubscribe;
  }, [controller]);

  const signIn = useCallback(
    (input: SignInInput) => controller.signIn(input),
    [controller]
  );

  const signUp = useCallback(
    (input: SignUpInput) => controller.signUp(input),
    [controller]
  );

  const signOut = useCallback(() => controller.signOut(), [controller]);

  const refreshSession = useCallback(
    () => controller.refreshSession(),
    [controller]
  );

  const verifyEmail = useCallback(
    (input: EmailVerificationInput) => controller.verifyEmail(input),
    [controller]
  );

  const requestOtp = useCallback(
    (input: OtpRequest) => controller.requestOtp(input),
    [controller]
  );

  const verifyOtp = useCallback(
    (input: OtpVerification) => controller.verifyOtp(input),
    [controller]
  );

  const verifyMfa = useCallback(
    (input: MfaVerifyInput) => controller.verifyMfa(input),
    [controller]
  );

  const requestPasswordReset = useCallback(
    (input: PasswordResetRequest) => controller.requestPasswordReset(input),
    [controller]
  );

  const resetPassword = useCallback(
    (input: PasswordResetInput) => controller.resetPassword(input),
    [controller]
  );

  const refreshAccessContextFromServer = useCallback(
    () => controller.refreshAccessContextFromServer(),
    [controller]
  );

  const value = useMemo<AuthContextValue>(
    () => ({
      ...snapshot,
      controller,
      signIn,
      signUp,
      signOut,
      refreshSession,
      verifyEmail,
      requestOtp,
      verifyOtp,
      verifyMfa,
      requestPasswordReset,
      resetPassword,
      refreshAccessContextFromServer,
    }),
    [
      snapshot,
      controller,
      signIn,
      signUp,
      signOut,
      refreshSession,
      verifyEmail,
      requestOtp,
      verifyOtp,
      verifyMfa,
      requestPasswordReset,
      resetPassword,
      refreshAccessContextFromServer,
    ]
  );

  return <AuthContext.Provider value={value}>{children}</AuthContext.Provider>;
}

export function useAuth(): AuthContextValue {
  const ctx = useContext(AuthContext);
  if (!ctx) {
    throw new Error('useAuth must be used inside <AuthProvider>.');
  }
  return ctx;
}
`;

  files['src/foundation/auth/index.ts'] = `export * from './auth.config';
export * from './AuthProvider';
`;

  return files;
}
